
# ==============================================================================
# PROCUREAI — integrations/sandbox_gst.py
# Client for Sandbox.co.in GST API.
#
# FRESHER EXPLANATION:
# This file is the "translator" between ProcureAI and the Indian
# government's GST portal (GSTN).
#
# GSTN is the government system that holds all GST data.
# It has an API but it's notoriously complex — requires encryption,
# OTP sessions, digital signatures.
#
# Sandbox.co.in is a company that handles all that complexity.
# They give us a simple REST API: "give me GSTR-2B for this GSTIN"
# and they return clean JSON.
#
# OUR JOB HERE:
# 1. Call Sandbox.co.in API correctly
# 2. Parse the response into our schema objects
# 3. Handle errors — API timeouts, invalid GSTIN, no data
# 4. Retry on temporary failures (rate limits, server errors)
#
# WHAT IS GSTR-2B?
# GSTR-2B is a monthly statement generated by GSTN on the 14th.
# It shows every purchase invoice where the SUPPLIER has filed
# their GSTR-1 (sales return). If a supplier hasn't filed,
# the invoice doesn't appear — and Ramesh loses that ITC.
# ==============================================================================

